"""Join synthetic Customer Voice aggregates to churn outcomes and existing model risk scores.

This is an exploratory linkage only. It does not train or modify the production model.
Because the linked support tickets and 10,000 customer rows are synthetic, outputs
must not be described as real-customer validation or evidence of NLP lift.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys
from typing import Any

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from src.predict import CustomerRiskScorer

CUSTOMER_COLUMNS = [
    "customerID", "gender", "SeniorCitizen", "Partner", "Dependents",
    "tenure", "PhoneService", "MultipleLines", "InternetService",
    "OnlineSecurity", "OnlineBackup", "DeviceProtection", "TechSupport",
    "StreamingTV", "StreamingMovies", "Contract", "PaperlessBilling",
    "PaymentMethod", "MonthlyCharges", "TotalCharges", "Churn",
]
VOICE_COLUMNS = [
    "customerID", "ticket_count", "negative_ticket_count",
    "negative_ticket_ratio", "mean_sentiment_score",
    "latest_sentiment_score", "latest_ticket_date",
]


def project_path(value: str) -> Path:
    path = Path(value)
    return path.resolve() if path.is_absolute() else (ROOT / path).resolve()


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--master",
        default="data/raw/telco_customer_risk_and_voice_master.csv",
        help="Combined customer master CSV.",
    )
    parser.add_argument(
        "--voice-features",
        default="data/processed/customer_voice_master/customer_text_features.csv",
        help="Customer-level sentiment aggregates generated by analyze_support_text.py.",
    )
    parser.add_argument(
        "--model",
        default="models/calibrated_research_rf.joblib",
        help="Existing calibrated production Random Forest artifact. It is loaded read-only.",
    )
    parser.add_argument(
        "--output-dir",
        default="data/processed/customer_voice_risk",
        help="Destination for joined records and exploratory summaries.",
    )
    return parser.parse_args()


def safe_corr(left: pd.Series, right: pd.Series, method: str) -> float | None:
    pair = pd.concat([left, right], axis=1).apply(pd.to_numeric, errors="coerce").dropna()
    if len(pair) < 2 or pair.iloc[:, 0].nunique() < 2 or pair.iloc[:, 1].nunique() < 2:
        return None
    if method == "spearman":
        pair = pair.rank(method="average")
    value = pair.iloc[:, 0].corr(pair.iloc[:, 1], method="pearson")
    return None if pd.isna(value) else float(value)


def summarize_by(grouped: pd.DataFrame, column: str) -> pd.DataFrame:
    rows: list[dict[str, Any]] = []
    for name, group in grouped.groupby(column, dropna=False, observed=False):
        rows.append({
            column: "Unknown" if pd.isna(name) else str(name),
            "customers": int(group["customerID"].nunique()),
            "mean_ticket_count": float(group["ticket_count"].mean()),
            "mean_negative_ticket_ratio": float(group["negative_ticket_ratio"].mean()),
            "median_negative_ticket_ratio": float(group["negative_ticket_ratio"].median()),
            "mean_sentiment_score": float(group["mean_sentiment_score"].mean()),
            "mean_calibrated_churn_probability": float(group["CalibratedChurnProbability"].mean()),
            "high_risk_customer_pct": float(
                group["CalibratedRiskLevel"].astype(str).eq("High").mean()
            ),
        })
    return pd.DataFrame(rows)


def main() -> None:
    args = parse_args()
    master_path = project_path(args.master)
    voice_path = project_path(args.voice_features)
    model_path = project_path(args.model)
    output_dir = project_path(args.output_dir)

    for required_path in (master_path, voice_path, model_path):
        if not required_path.exists():
            raise SystemExit(f"Required file not found: {required_path}")

    master = pd.read_csv(master_path)
    voice = pd.read_csv(voice_path)

    missing_customer = [c for c in CUSTOMER_COLUMNS if c not in master.columns]
    missing_voice = [c for c in VOICE_COLUMNS if c not in voice.columns]
    if missing_customer:
        raise SystemExit(f"Master CSV is missing required customer fields: {missing_customer}")
    if missing_voice:
        raise SystemExit(f"Voice aggregate file is missing required fields: {missing_voice}")
    if master["customerID"].duplicated().any():
        raise SystemExit("Master CSV contains duplicate customerID values. Resolve IDs before joining.")
    if voice["customerID"].duplicated().any():
        raise SystemExit("Voice aggregate file must contain exactly one row per customerID.")

    master["customerID"] = master["customerID"].astype(str)
    voice["customerID"] = voice["customerID"].astype(str)
    synthetic_mask = master["customerID"].str.startswith("SYNTH_")
    if "record_origin" in master.columns:
        synthetic_mask &= master["record_origin"].astype(str).eq("synthetic_customer_record")
    synthetic = master.loc[synthetic_mask, CUSTOMER_COLUMNS].copy()
    synthetic_metadata = master.loc[synthetic_mask, ["customerID"] + (["record_origin"] if "record_origin" in master.columns else [])].copy()

    if synthetic.empty:
        raise SystemExit("No SYNTH_ customer records were found in the master CSV.")
    if not voice["customerID"].str.startswith("SYNTH_").all():
        raise SystemExit(
            "Voice aggregates contain non-SYNTH_ IDs. This experiment expects only the newly generated synthetic customers."
        )

    # Ensure feature columns have numeric values where expected.
    for col in ("TotalCharges", "MonthlyCharges", "tenure", "SeniorCitizen"):
        synthetic[col] = pd.to_numeric(synthetic[col], errors="coerce")
    for col in (
        "ticket_count", "negative_ticket_count", "negative_ticket_ratio",
        "mean_sentiment_score", "latest_sentiment_score",
    ):
        voice[col] = pd.to_numeric(voice[col], errors="coerce")

    merged = synthetic_metadata.merge(
        synthetic, on="customerID", how="inner", validate="one_to_one"
    ).merge(
        voice[VOICE_COLUMNS], on="customerID", how="left", validate="one_to_one", indicator=True
    )
    unmatched = int(merged["_merge"].ne("both").sum())
    merged = merged.drop(columns="_merge")
    if unmatched:
        raise SystemExit(
            f"{unmatched:,} synthetic customers do not have voice features. "
            "Re-run scripts.analyze_support_text.py before this analysis."
        )

    # Reuse the existing production scorer exactly as-is. No model is trained or saved here.
    scorer = CustomerRiskScorer(model_path)
    scored = scorer.score(synthetic.copy())
    risk_cols = [
        "customerID", "CalibratedChurnProbability", "CalibratedRiskLevel",
        "RevenueAtRisk", "RetentionPriorityScore", "RetentionPriority",
        "RetentionRecommendation",
    ]
    merged = merged.merge(scored[risk_cols], on="customerID", how="left", validate="one_to_one")

    if merged["CalibratedChurnProbability"].isna().any():
        raise SystemExit("Model scoring produced missing calibrated churn probabilities.")

    # Keep provenance explicit in every joined row.
    merged["analysis_population"] = "synthetic_only_exploratory"
    merged["support_text_is_synthetic"] = True
    merged["sentiment_is_model_prediction"] = True

    by_churn = summarize_by(merged, "Churn").sort_values("Churn")
    by_risk = summarize_by(merged, "CalibratedRiskLevel")
    priority_order = ["Low", "Moderate", "High", "Critical"]
    by_priority = summarize_by(merged, "RetentionPriority")
    if not by_priority.empty:
        by_priority["_order"] = by_priority["RetentionPriority"].map(
            {name: index for index, name in enumerate(priority_order)}
        )
        by_priority = by_priority.sort_values("_order").drop(columns="_order")

    corr_rows = []
    for feature in ("negative_ticket_ratio", "mean_sentiment_score", "latest_sentiment_score"):
        corr_rows.extend([
            {
                "sentiment_feature": feature,
                "comparison": "calibrated_churn_probability",
                "method": "pearson",
                "correlation": safe_corr(merged[feature], merged["CalibratedChurnProbability"], "pearson"),
            },
            {
                "sentiment_feature": feature,
                "comparison": "calibrated_churn_probability",
                "method": "spearman",
                "correlation": safe_corr(merged[feature], merged["CalibratedChurnProbability"], "spearman"),
            },
            {
                "sentiment_feature": feature,
                "comparison": "synthetic_churn_label_yes_no",
                "method": "spearman",
                "correlation": safe_corr(
                    merged[feature], merged["Churn"].map({"No": 0, "Yes": 1}), "spearman"
                ),
            },
        ])
    correlations = pd.DataFrame(corr_rows)

    output_dir.mkdir(parents=True, exist_ok=True)
    joined_path = output_dir / "customer_voice_risk_joined.csv"
    churn_path = output_dir / "voice_risk_summary_by_churn.csv"
    risk_path = output_dir / "voice_risk_summary_by_risk.csv"
    priority_path = output_dir / "voice_risk_summary_by_priority.csv"
    corr_path = output_dir / "voice_risk_correlations.csv"

    output_columns = [
        "customerID", "Churn", "record_origin", "analysis_population",
        "support_text_is_synthetic", "sentiment_is_model_prediction",
        "ticket_count", "negative_ticket_count", "negative_ticket_ratio",
        "mean_sentiment_score", "latest_sentiment_score", "latest_ticket_date",
        "CalibratedChurnProbability", "CalibratedRiskLevel", "RevenueAtRisk",
        "RetentionPriorityScore", "RetentionPriority", "RetentionRecommendation",
    ]
    output_columns = [c for c in output_columns if c in merged.columns]
    merged[output_columns].to_csv(joined_path, index=False)
    by_churn.to_csv(churn_path, index=False)
    by_risk.to_csv(risk_path, index=False)
    by_priority.to_csv(priority_path, index=False)
    correlations.to_csv(corr_path, index=False)

    negative_share = float(merged["negative_ticket_ratio"].mean())
    mean_sentiment = float(merged["mean_sentiment_score"].mean())
    mean_probability = float(merged["CalibratedChurnProbability"].mean())
    run_summary = {
        "analysis_type": "synthetic_only_exploratory_customer_voice_risk_join",
        "master_input": str(master_path),
        "voice_features_input": str(voice_path),
        "model_artifact_loaded_read_only": str(model_path),
        "customers_in_master": int(len(master)),
        "synthetic_customers_joined": int(len(merged)),
        "voice_customers_unmatched": unmatched,
        "support_tickets_represented": int(merged["ticket_count"].sum()),
        "mean_customer_negative_ticket_ratio": negative_share,
        "mean_model_sentiment_score": mean_sentiment,
        "mean_existing_model_churn_probability": mean_probability,
        "model_retrained": False,
        "production_model_changed": False,
        "real_customer_voice_available": False,
        "time_safe_prediction_cutoff_available": False,
        "limitations": [
            "All joined support messages and all joined SYNTH_ customer records are synthetic.",
            "Synthetic customer rows were created by class-conditional empirical resampling and perturbation from IBM Telco source rows.",
            "Synthetic support-message tone was randomized independently of the Churn column, but message content reflects customer service attributes.",
            "The Churn label is synthetic/inherited from the synthetic row-generation process, not a new independent outcome observation.",
            "The support ticket dates are simulated and no prediction as-of date was supplied; this is not a time-safe predictive evaluation.",
            "Correlation or group differences here are descriptive only and cannot establish that sentiment improves churn prediction or retention.",
            "DistilBERT SST-2 is a general English sentiment model, not a telecom-specific validated classifier.",
        ],
        "outputs": {
            "customer_level_join": str(joined_path),
            "summary_by_churn_label": str(churn_path),
            "summary_by_risk_level": str(risk_path),
            "summary_by_retention_priority": str(priority_path),
            "correlations": str(corr_path),
        },
    }
    summary_path = output_dir / "run_summary.json"
    summary_path.write_text(json.dumps(run_summary, indent=2), encoding="utf-8")
    print(json.dumps(run_summary, indent=2))


if __name__ == "__main__":
    main()
